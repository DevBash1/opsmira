#!/usr/bin/env node
// Copies the lucide icon geometry the video needs out of the product's own src/components/Icons.tsx
// into src/kit/icons.generated.ts, so the icons are identical to the real UI. Reads only; never edits src/.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = path.resolve(ROOT, "../src/components/Icons.tsx");
const NEEDED = [
  "terminal", "server", "check", "arrow-up", "arrow-up-right", "refresh-cw", "scroll-text", "key-round",
  "triangle-alert", "play", "square", "plus", "history", "file-text", "bookmark", "box", "corner-down-right",
  "sun", "moon", "sparkles", "eye", "circle-check", "info", "log-out", "activity", "cpu", "loader-circle", "droplet", "orbit",
];

const src = fs.readFileSync(SOURCE, "utf8");

function grab(name) {
  const at = src.indexOf(`const ${name}`);
  if (at < 0) return {};
  const open = src.indexOf("{", src.indexOf("=", at));
  let depth = 0;
  let end = open;
  for (; end < src.length; end++) {
    if (src[end] === "{") depth++;
    else if (src[end] === "}" && --depth === 0) break;
  }
  return new Function(`return (${src.slice(open, end + 1)})`)();
}

const paths = grab("PATHS");
const strokes = grab("STROKES");
const out = {};
for (const name of NEEDED) {
  if (strokes[name]) out[name] = { stroke: true, d: strokes[name] };
  else if (paths[name]) out[name] = { stroke: false, d: paths[name] };
  else console.warn(`icon not found: ${name}`);
}

fs.mkdirSync(path.join(ROOT, "src/kit"), { recursive: true });
fs.writeFileSync(
  path.join(ROOT, "src/kit/icons.generated.ts"),
  `// Generated by scripts/extract-icons.mjs from the product's Icons.tsx (lucide geometry). Do not edit.\n` +
    `export const ICON_DATA: Record<string, { stroke: boolean; d: string[] }> = ${JSON.stringify(out, null, 1)};\n` +
    `export type IconName = ${Object.keys(out).map((k) => JSON.stringify(k)).join(" | ")};\n`,
);
console.log(`wrote ${Object.keys(out).length} icons`);
